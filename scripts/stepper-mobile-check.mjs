import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 320, height: 700 } });
await page.goto("http://localhost:4173", { waitUntil: "networkidle" });
await page.waitForTimeout(800);
const log = [];
const ok = (m) => log.push("OK   " + m);
const fail = (m) => log.push("FAIL " + m);
await page.getByRole("button", { name: /Preciso de uma profissional/ }).first().click();
await page.waitForTimeout(700);
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1);
overflow ? fail("320px: overflow no wizard") : ok("320px: sem overflow no wizard");
await page.getByRole("radio", { name: /Babá/ }).click();
await page.waitForTimeout(1000);
const banner = await page.getByRole("dialog").getByText("Babá", { exact: true }).isVisible();
banner ? ok("320px: banner do serviço visível") : fail("320px: banner ausente");
const cardH = await page.getByRole("radio", { name: /Meu filho/ }).boundingBox();
cardH && cardH.y + cardH.height <= 700 ? ok("320px: opções tocáveis na viewport") : fail("320px: opções fora da viewport");
await page.getByRole("radio", { name: "Meu filho" }).click();
await page.getByRole("button", { name: "Continuar" }).click();
await page.waitForTimeout(600);
const next = await page.getByText("Quando você precisa?").isVisible();
next ? ok("320px: navegação funciona") : fail("320px: navegação quebrou");
await browser.close();
console.log(log.join("\n"));
